// Bundle the CLI into skills/sam/scripts/sam.mjs (single file, Node 20+, no npm install for the skill).
import { build } from 'esbuild';
import { readFileSync } from 'node:fs';
import { createRequire } from 'node:module';
import { fileURLToPath } from 'node:url';
import { inlineAssets } from './inline-assets.mjs';

const temmlAsString = {
  name: 'temml-as-string',
  setup(b) {
    b.onResolve({ filter: /^temml$/ }, () => ({ path: 'temml', namespace: 'temml-string' }));
    b.onLoad({ filter: /.*/, namespace: 'temml-string' }, () => {
      const min = readFileSync(createRequire(import.meta.url).resolve('temml/dist/temml.min.js'), 'utf8');
      return {
        loader: 'js',
        contents: `import { runInThisContext } from 'node:vm';
export default runInThisContext(${JSON.stringify(`(function () {\n${min}\nreturn temml;\n})()`)});\n`,
      };
    });
  },
};

await build({
  entryPoints: [fileURLToPath(new URL('../bin/sam.js', import.meta.url))],
  outfile: fileURLToPath(new URL('../skills/sam/scripts/sam.mjs', import.meta.url)),
  bundle: true,
  platform: 'node',
  format: 'esm',
  target: 'node20',
  legalComments: 'eof',
  banner: { js: '// sam CLI — generated by scripts/build.mjs. Source: https://github.com/CannonPanda/sam' },
  plugins: [inlineAssets, temmlAsString],
  logLevel: 'info',
});
